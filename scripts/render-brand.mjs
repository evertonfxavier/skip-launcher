// Renders the brand images from assets/logo.svg and assets/social-preview.svg.
// Usage: pnpm run brand
//   assets/logo.png            512 px, README and plugin store
//   assets/logo-128.png        128 px, small uses
//   assets/social-preview.png  1280x640, GitHub "social preview" (upload it in the repository settings)
import { Resvg } from "@resvg/resvg-js";
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const ROOT = new URL("..", import.meta.url).pathname;
const A = (f) => join(ROOT, "assets", f);

function render(svgFile, outFile, width, fonts = false) {
  const svg = readFileSync(A(svgFile), "utf8");
  const png = new Resvg(svg, {
    fitTo: { mode: "width", value: width },
    font: fonts ? { loadSystemFonts: true, defaultFontFamily: "Helvetica Neue" } : undefined,
  }).render().asPng();
  writeFileSync(A(outFile), png);
  console.log(`${outFile}  ${(png.length / 1024).toFixed(0)} KB`);
}

// The social preview is composed from the logo, so the two can never drift apart.
const logo = readFileSync(A("logo.svg"), "utf8");
const inner = logo.slice(logo.indexOf(">", logo.indexOf("<svg")) + 1, logo.lastIndexOf("</svg>"));
const social = `<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="640" viewBox="0 0 1280 640">
  <!-- Generated by scripts/render-brand.mjs from assets/logo.svg - do not edit -->
  <defs>
    <linearGradient id="sbg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#1D2132"/>
      <stop offset="1" stop-color="#0F121B"/>
    </linearGradient>
  </defs>
  <rect width="1280" height="640" fill="url(#sbg)"/>
  <rect x="0" y="0" width="12" height="640" fill="#FFA63D"/>
  <svg x="100" y="160" width="320" height="320" viewBox="0 0 256 256">${inner}</svg>
  <text x="480" y="300" font-family="Helvetica Neue, Arial, sans-serif" font-weight="700" font-size="88" fill="#FFFFFF">Skip Launcher</text>
  <text x="484" y="364" font-family="Helvetica Neue, Arial, sans-serif" font-size="36" fill="#AFC1D1">Start your games straight into the game,</text>
  <text x="484" y="414" font-family="Helvetica Neue, Arial, sans-serif" font-size="36" fill="#AFC1D1">no launcher window, controller only.</text>
  <text x="484" y="486" font-family="Helvetica Neue, Arial, sans-serif" font-size="28" fill="#7F8AA3">Decky Loader plugin  ·  open source  ·  BSD-3-Clause</text>
</svg>
`;
writeFileSync(A("social-preview.svg"), social);

render("logo.svg", "logo.png", 512);
render("logo.svg", "logo-128.png", 128);
render("social-preview.svg", "social-preview.png", 1280, true);
