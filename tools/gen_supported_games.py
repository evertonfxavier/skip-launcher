#!/usr/bin/env python3
"""Generate the list of supported games from the profile registry and the game pages.

    python3 tools/gen_supported_games.py            write SUPPORTED_GAMES.md
    python3 tools/gen_supported_games.py --check    exit 1 if it is out of date (the tests use this)

Sources of truth - never edit the generated file by hand:
  * skip_launcher.profiles.PROFILES      which games exist, what they skip, the settings they offer
  * docs/games/<appid>-*.md              the "Summary" and "Support level" rows of "At a glance"
                                         and every "- NOT verified:" line

Support level (a row of every game page, exactly one of these):
  confirmed         somebody saw it work on the Deck
  partly confirmed  some of it was seen, some only verified by tests
  unconfirmed       verified by tests / on the files only; nobody has reported the result yet
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "py_modules"))

LEVELS = {
    "confirmed": {"icon": "✅", "en": "confirmed"},
    "partly confirmed": {"icon": "🟡", "en": "partly confirmed"},
    "unconfirmed": {"icon": "⚪", "en": "unconfirmed"},
}
GROUPS = {"video": "Video", "detail": "Detail", "game": "Game"}


class PageError(Exception):
    pass


def read_page(root, appid):
    pages = sorted((root / "docs" / "games").glob("%s-*.md" % appid))
    if not pages:
        raise PageError("docs/games/%s-*.md is missing" % appid)
    text = pages[0].read_text()
    rows = {}
    for line in text.splitlines():
        m = re.match(r"^\|\s*([^|]+?)\s*\|\s*(.*?)\s*\|\s*$", line)
        if m and m.group(1) in ("Summary", "Support level"):
            rows[m.group(1)] = m.group(2)
    for key in ("Summary", "Support level"):
        if not rows.get(key):
            raise PageError("%s has no '%s' row in its 'At a glance' table" % (pages[0].name, key))
    if rows["Support level"] not in LEVELS:
        raise PageError("%s: Support level %r must be one of: %s" % (
            pages[0].name, rows["Support level"], ", ".join(LEVELS)))
    unverified = [line.split("NOT verified:", 1)[1].strip()
                  for line in text.splitlines() if line.startswith("- NOT verified:")]
    return {"page": pages[0].name, "summary": rows["Summary"], "level": rows["Support level"],
            "unverified": unverified}


def collect(root=ROOT):
    from skip_launcher.profiles import PROFILES
    games = []
    for appid, profile in PROFILES.items():
        games.append({"appid": appid, "name": profile.name, "profile": profile, **read_page(root, appid)})
    games.sort(key=lambda g: g["name"].lower())
    return games


def settings_by_group(profile):
    out = {}
    for s in profile.settings:
        out.setdefault(s.group, []).append(s.label)
    return out


def render_supported_games(root=ROOT):
    games = collect(root)
    out = [
        "# Supported games",
        "",
        "<!-- GENERATED by tools/gen_supported_games.py - do not edit by hand. Run the tool after adding or changing a game. -->",
        "",
        "Skip Launcher works **game by game**: every launcher window keeps its choices somewhere different, so each game "
        "needs its own *profile*. This is the complete list of games the plugin can start without their launcher window "
        "today (%d). It is generated from the code, so it is always in step with the plugin." % len(games),
        "",
        "## How much can you trust each game?",
        "",
        "| Level | Meaning |",
        "|-------|---------|",
        "| %s **confirmed** | Someone played the game on a Steam Deck and saw it start straight into the game and the settings work |" % LEVELS["confirmed"]["icon"],
        "| %s **partly confirmed** | Some of it was seen on the Deck; the rest is verified by tests only |" % LEVELS["partly confirmed"]["icon"],
        "| %s **unconfirmed** | Verified by tests and on the real files, but nobody has reported the result on a Deck yet |" % LEVELS["unconfirmed"]["icon"],
        "",
        "Whatever the level: no game file is touched to skip the launcher (only the launch option of the game in Steam "
        "changes, and turning the switch off removes just what the plugin added), nothing is written while the game is "
        "running, installing or updating, and **Put the original settings back** restores every value the plugin "
        "changed, key by key.",
        "",
        "## At a glance",
        "",
        "| Game | Steam ID | Skips with | Settings | Support | Technical notes |",
        "|------|----------|-------|----------|---------|-----------------|",
    ]
    for g in games:
        p, lv = g["profile"], LEVELS[g["level"]]
        skips = "`%s`" % (p.skip_args if p.skip_args else p.launcher_exe)
        out.append("| **%s** | [%s](https://store.steampowered.com/app/%s) | %s | %d | %s %s | [notes](docs/games/%s) |" % (
            g["name"], g["appid"], g["appid"], skips, len(p.settings), lv["icon"], lv["en"], g["page"]))
    out += ["", "## Details per game", "", "Click a game to see what it changes and what is not confirmed yet.", ""]
    for g in games:
        p, lv = g["profile"], LEVELS[g["level"]]
        out += [
            "<details>",
            "<summary><b>%s (%s)</b> · %s %s</summary>" % (g["name"], g["appid"], lv["icon"], lv["en"]),
            "",
            g["summary"],
            "",
        ]
        if p.skip_args:
            out += ["- **Skips:** the startup dialog of `%s`" % p.game_exe,
                    "- **How:** the launch option `%%command%% %s` (the game's own switch); no game file is modified" % p.skip_args]
        else:
            out += ["- **Skips:** `%s`, so Steam starts `%s` instead" % (p.launcher_exe, p.game_exe),
                    "- **How:** a launch option that rewrites that one argument of Steam's command; no game file is modified"]
        groups = settings_by_group(p)
        for key in ("video", "detail", "game"):
            if key in groups:
                out.append("- **%s settings:** %s" % (GROUPS[key], ", ".join(groups[key])))
        where = "the Windows registry of the game's Proton prefix (`%s`)" if p.config_format == "reg" \
            else "`%s` (inside the game's Proton prefix)"
        out.append("- **Settings file:** " + where % p.config_rel.split("/")[-1])
        if g["unverified"]:
            out.append("- **Not confirmed yet:** " + " ".join(u[:1].upper() + u[1:].rstrip(".") + "." for u in g["unverified"]))
        out += ["- **Links:** [Steam store](https://store.steampowered.com/app/%s) · [technical notes](docs/games/%s)" % (
            g["appid"], g["page"]), "", "</details>", ""]
    out += [
        "## Not on the list?",
        "",
        "Only games whose launcher window can be skipped without touching the game's files are accepted. Games with "
        "anti-cheat or online ranked play are out of scope.",
        "",
    ]
    return "\n".join(out)


def targets(root=ROOT):
    """(path, new content) for every generated file."""
    return [(root / "SUPPORTED_GAMES.md", render_supported_games(root))]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if something is stale")
    ap.add_argument("--root", default=str(ROOT))
    args = ap.parse_args(argv)
    root = Path(args.root)
    try:
        files = targets(root)
    except PageError as exc:
        print("error:", exc, file=sys.stderr)
        return 2
    stale = [p for p, content in files if not p.exists() or p.read_text() != content]
    if args.check:
        for p in stale:
            print("out of date:", p.relative_to(root), file=sys.stderr)
        return 1 if stale else 0
    for p, content in files:
        if p in stale:
            p.write_text(content)
            print("updated", p.relative_to(root))
    if not stale:
        print("already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
